def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    views=render();stale=[]
    for name,body in views.items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8')!=body:stale.append(name)
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(body,encoding='utf-8')
    if stale:
        print('Stale generated files:\n'+'\n'.join(stale),file=sys.stderr);return 1
    print(f"{'Checked' if args.check else 'Generated'} {len(views)} reading views.");return 0

if __name__=='__main__':sys.exit(main())
