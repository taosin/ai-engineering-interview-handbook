#!/usr/bin/env python3
"""Render all reading views from JSON. Use --check in CI to reject stale views."""
from __future__ import annotations
import argparse
from collections import Counter
from pathlib import Path
import os
import sys
from validate import ROOT, load_data, validate_data, require
from learning import load_learning, validate_learning, render_learning, guide_path, lab_path
from roadmap import load_roadmap, validate_roadmap, render_roadmap, render_role_growth

BANNER = '<!-- Generated by scripts/build.py. Edit data/*.json, then rebuild. -->\n\n'
STATUS_LABELS = {'historical':'沿用首版核实记录', 'original':'本轮原帖正文', 'platform-index':'本轮平台公开展示', 'search-index':'本轮搜索索引正文；直链未复核'}

def render():
    qs, ss, cat = load_data()
    validate_data(qs, ss, cat)
    learning = load_learning(ROOT)
    validate_learning(learning, qs, cat)
    roadmap = load_roadmap(ROOT)
    validate_roadmap(roadmap, qs, cat, learning)
    topics = {t['id']: t for t in cat['topics']}
    sources = {s['id']: s for s in ss}
    questions = {q['id']: q for q in qs}
    counts = Counter(q['topic'] for q in qs)
    out = {}
    def rel(file, target):
        return Path(os.path.relpath(target, Path(file).parent)).as_posix()
    def qlink(file, q):
        return f"[{q['id']}]({rel(file, topics[q['topic']]['file'])}#{q['id'].lower()})"
    guides = {g['id']: g for g in learning['guides']}
    labs = {lab['id']: lab for lab in learning['labs']}
    def glink(file, gid):
        guide = guides[gid]
        return f"[{gid} · {guide['title']}]({rel(file,guide_path(guide))})"
    def llink(file, lid):
        lab = labs[lid]
        return f"[{lid} · {lab['title']}]({rel(file,lab_path(lab))})"
    def qid_link(file, qid):
        return qlink(file, questions[qid])
    def table(file, selection):
        lines = ['| 题号 | 问题 | 主题 | 题型 |', '| --- | --- | --- | --- |']
        for q in selection:
            lines.append(f"| {qlink(file,q)} | {q['question'].replace('|',' / ')} | {topics[q['topic']]['title']} | {cat['question_types'][q['question_type']]} |")
        return '\n'.join(lines)
    def save(file, lines):
        require((ROOT / file).resolve().is_relative_to(ROOT), f'Output escapes repository: {file}')
        require(file not in out, f'Duplicate generated output: {file}')
        out[file] = BANNER + '\n'.join(lines).rstrip() + '\n'
    for file, lines in render_learning(learning, lambda file, qid: qlink(file, questions[qid])).items():
        save(file, lines)
    for file, lines in render_roadmap(roadmap, qid_link, glink, llink).items():
        save(file, lines)
    for topic in cat['topics']:
        f = topic['file']; selected = [q for q in qs if q['topic'] == topic['id']]
        lines = [f"# {topic['title']}", '', f"{len(selected)} 道题 · [全部题目]({rel(f,'questions/README.md')}) · [岗位路线]({rel(f,'paths/README.md')}) · [题型索引]({rel(f,'indexes/by-type.md')})", '', '**准备目标（编者建议）**：'+topic['focus'], '', '> 题目是公开面经的归纳改写，不是逐字引述或企业官方题库。日期与核实状态请看每条来源。', '']
        lines += [f"- {qlink(f,q)} {q['question']}" for q in selected]
        lines += ['']
        for q in selected:
            lines += [f"## {q['id']}", '', q['question'], '', f"**题型**：{cat['question_types'][q['question_type']]} · **适用岗位（编者建议）**：{'、'.join(q['roles'])}", '']
            if q['temporal_scope']=='边界补充':lines+=['**时间边界**：该题仅有首版边界材料支持，不能确认面试发生在当前半年窗口内。','']
            for sid in q['source_ids']:
                s = sources[sid]
                lines += [f"- [{sid} · {s['title']}]({rel(f,'SOURCES.md')}#{sid.lower()}) — {q['source_locators'][sid].rstrip('。')}。"]
            lines += ['']
            for follow_up in q.get('follow_ups', []):
                sid = follow_up['source_id']
                lines += ['**来源支持的追问变体（不单独计题）**：'+follow_up['question'], '', f"来源：[{sid}]({rel(f,'SOURCES.md')}#{sid.lower()}) — {follow_up['locator'].rstrip('。')}。", '']
            related = [g for g in learning['guides'] if q['id'] in g['question_ids']]
            if related:
                lines += ['**原创答题指南**：' + ' · '.join(f"[{g['id']} · {g['title']}]({rel(f,guide_path(g))})" for g in related), '']
        for qid in cat.get('legacy_anchors',{}).get(f,[]):
            q = questions[qid]
            lines += [f'## {qid}', '', f"本题已移至 {qlink(f,q)} {q['question']}。保留此锚点兼容旧链接。", '']
        save(f,lines)
    f='questions/README.md'
    save(f,['# 全部题目','',f"{len(qs)} 道题；题号稳定，按编号排列。可用页面搜索查关键词，也可从[岗位路线](../paths/README.md)或[题型索引](../indexes/by-type.md)开始。",'',table(f,qs),'','[返回首页](../README.md)'])
    f='indexes/by-type.md';lines=['# 按题型练习','','题型描述回答方式，主题描述知识领域；同一题只指定一个主要题型，不表示只能用一种方式练习。','']
    for kind,label in cat['question_types'].items():
        lines += [f'## {label}', '', table(f,[q for q in qs if q['question_type']==kind]),'']
    lines += ['[返回首页](../README.md)'];save(f,lines)
    save('paths/README.md',['# 按岗位学习与复习','','先用[起点自测](../roadmap/start.md)确定缺口，再沿[学习主线](../roadmap/milestones.md)推进。M5 只选择一个岗位分支；各分支第一个交付点配合 M5 对照验收，之后回到 M6 整理作品。其余交付点用于长期成长。','','以下路线与岗位标签均为编者建议，不代表企业统一要求。每页先列项目交付与验证，再提供面试复习题选。','']+[f"- [{role['name']}]({role['id']}.md)：{role['intro']}" for role in cat['roles']]+['','[复习与查漏](../roadmap/review.md) · [长期成长](../roadmap/growth.md) · [返回首页](../README.md)'])
    for role in cat['roles']:
        f=f"paths/{role['id']}.md"
        lines=[f"# {role['name']}学习与复习路线",'',role['intro'],'']
        lines += render_role_growth(roadmap, role['id'], qid_link, glink, llink)
        lines += ['', '## 面试复习题选', '', '下面是按主题组织的精选题，不是额外的成长阶段。先闭卷回答，再结合项目记录与来源追问检查缺口。', '']
        for i,stage in enumerate(role['stages'],1):
            lines += [f"### 专题 {i}：{stage['title']}", '', stage['goal'], '']
            lines += [f"- {qlink(f,questions[qid])} {questions[qid]['question']}" for qid in stage['ids']]
            lines += ['']
        selected=[q for q in qs if role['name'] in q['roles']]
        lines += ['## 全部适用题', '',f'共 {len(selected)} 道。这里包含新增题，按主题定位，避免重复阅读多份题目正文。','']
        for topic in cat['topics']:
            items=[q for q in selected if q['topic']==topic['id']]
            if items:lines += [f"- **{topic['title']}**："+' · '.join(qlink(f,q) for q in items)]
        related = [g for g in learning['guides'] if any(role['name'] in questions[qid]['roles'] for qid in g['question_ids'])]
        lines += ['', '## 回答与验证', '', '以下为本项目原创研习材料；可以先回答关联题，再用指南和故障练习检查方案。', '']
        lines += [f"- [{g['id']} · {g['title']}]({rel(f,guide_path(g))})" for g in related]
        lines += ['', '[全部故障练习](../learning/README.md) · [项目复盘模板](../templates/project-evidence.md)']
        lines += ['','[全部岗位](README.md) · [返回首页](../README.md)'];save(f,lines)
    f='SOURCES.md';lines=['# 来源档案','',f"{len(ss)} 个来源条目。来源条目数不是公司数、作者数或独立面试场次数。",'', '核实状态区分原帖正文、平台展示、搜索索引和首版历史记录。原帖真实性未获企业独立确认；日期始终按标注口径读取。','']
    for s in ss:
        v=s['verification']
        lines += [f"## {s['id']}",'',f"**[{s['title']}]({s['url']})**",'',f"- 发布平台：{s['platform']}",f"- 时间记录：{s['date_label']}（{s['date_kind']}）",f"- 原始时间显示：{s['date_evidence']['raw_label']}",f"- 年份依据：{s['date_evidence']['year_basis']}",f"- 核实状态：{STATUS_LABELS[v['status']]}；检查日期 {v['checked_on']}",f"- 阅读位置：[公开链接]({v['evidence_url']})；{v['note']}",f"- 说明：{s['notes']}"]
        if s.get('reported_role'):lines += [f"- 原帖岗位／招聘信息：{s['reported_role']}；{s.get('recruitment_type','未明确')}"]
        refs=[q for q in qs if s['id'] in q['source_ids'] or any(follow_up['source_id']==s['id'] for follow_up in q.get('follow_ups',[]))]
        lines += ['- 对应题目：'+' · '.join(qlink(f,q) for q in refs),'']
    lines+=['## 平台覆盖与访问限制','','当前题库以牛客和 LINUX DO 的公开材料为主。本轮新增来源不代表覆盖全部平台。首版小红书部分笔记需要登录或链接失效，脉脉未取得时间与问题都明确的近期原帖；没有把转载当作这些平台的一手采集。','','仓库中的“小红书”常指应聘公司，发布平台请看各条记录。仅搜索索引可读的内容会单独标记，不能当作原帖此刻仍可访问。','','[整理方法](METHODOLOGY.md) · [返回首页](README.md)'];save(f,lines)
    f='README.md'
    lines=['# AI Engineering Interview Handbook','','面向 **AI 全栈、Agent 工程师、LLM 应用开发、Agent Infra** 的中文面试与工程成长手册。','',f"**{len(qs)} 道归纳题 · {len(cat['topics'])} 个主题 · {len(ss)} 个来源条目 · {len(cat['roles'])} 条岗位路线 · {len(cat['question_types'])} 类练习题型**",'', f"另有 **{len(learning['guides'])} 份原创答题指南、{len(learning['labs'])} 个故障练习和 1 份项目复盘模板**，单独标注内容类型与技术依据。", '', '从[起点自测](roadmap/start.md)出发，沿能力里程碑学习，用题库检验理解，用故障与项目记录验证实现，再通过复习和岗位深化持续成长。面经问题保留稳定题号、原帖定位和日期口径。', '', f"学习体系提供 **{len(roadmap['entries'])} 类起点、{sum(not m['optional'] for m in roadmap['milestones'])} 个主线里程碑、{len(roadmap['roles'])} 个岗位分支**，另有复习循环、面试前两周安排与长期成长标准。",'', '## 选择入口','', '| 你想做什么 | 入口 |','| --- | --- |','| 不知道从哪里开始 | [学习与成长总览](roadmap/README.md) · [起点自测](roadmap/start.md) |','| 按阶段完成一个项目 | [能力里程碑与验收](roadmap/milestones.md) |','| 了解六维能力测试设计 | [测评与雷达图方案](docs/assessment-design.md)（方案，待实施） |','| 按目标岗位准备 | [4 条岗位学习与复习路线](paths/README.md) |','| 学过但记不牢，或临近面试 | [复习机制](roadmap/review.md) · [面试前两周](roadmap/interview-sprint.md) |','| 已有作品，继续提升 | [长期成长标准](roadmap/growth.md) |','| 查找具体问题 | [全部题目](questions/README.md) |','| 练设计、排障、评测或编码 | [按题型练习](indexes/by-type.md) |','| 理清回答、用故障验证方案 | [原创答题指南与练习](learning/README.md) |','| 准备可核对的项目经历 | [项目复盘模板](templates/project-evidence.md) |','| 检查原帖及日期 | [来源档案](SOURCES.md) |','| 理解统计范围与不确定性 | [整理方法](METHODOLOGY.md) |','', '## 主题目录','', '| 主题 | 题数 | 准备重点 |','| --- | --- | --- |']
    for t in cat['topics']:lines += [f"| [{t['title']}]({t['file']}) | {counts[t['id']]} | {t['focus']} |"]
    lines += ['', '## 资料范围','', f"最新整理日期：**{cat['curated_through']}**。本轮目标检索窗口为 **{'—'.join(cat['current_window'])}**；首版窗口为 **{'—'.join(cat['original_window'])}**。保留历史材料及边界说明，不将全部旧来源的核实日期批量改成今天。",'', '原帖的发布时间、编辑时间与面试发生时间分别标注。新增材料包含 10 月记录，但不能据此宣称每道题都是最近半年实际出题。S03 为 6 月发布的 4—5 月复盘，单场日期不明，仍作边界补充。','', '本项目不是企业官方题库，也不是招聘市场的代表性统计，不承诺“最高频”或“必考”。部分原帖访问不稳定，搜索索引、平台展示与原帖正文在[来源档案](SOURCES.md)中分开标记。','', '## 如何使用','', '- 先用自测选择起点，建立[个人学习计划](templates/study-plan.md)，每周只推进一个主要产物。','- 在 M5 选择一个岗位分支；以验收证据进入下一阶段，有证据的已有能力可以跳过重复学习。','- 用[复习记录表](templates/review-log.csv)安排下一次闭卷尝试；知识、实现或证据不足时回到对应阶段修复。','- 项目表达建议：业务目标 → 约束 → 方案选择 → 实现 → 失败案例 → 验证结果。','- 编码题先明确输入输出、边界和复杂度；原帖条件不完整时应主动说明假设。','- 先独立回答，再参考指南并完成故障练习；把真实证据填入复盘模板。指南是编者建议，不是企业标准答案。','- 面经题、原创指南和合成练习分别计数。技术资料支持机制解释，不能替代原帖证明题目出处。','', '## 数据与维护','', '题目、来源、分类、研习与成长规划保存在 [`data/`](data/README.md) 的 JSON 中。题目、路线、指南、练习和索引统一生成；个人计划、复习记录与项目复盘模板单独编辑。','', '```sh','python3 scripts/build.py','python3 scripts/validate.py','python3 scripts/build.py --check','```','', '本地筛选与抽题（Python 3.10+，无需第三方依赖）：','', '```sh','python3 scripts/practice.py --role "AI 全栈" --type design --limit 5','python3 scripts/practice.py --topic reliability --sample 3 --seed 42','```','', '[贡献指南](CONTRIBUTING.md) · [更新记录](CHANGELOG.md) · [提交 Issue](https://github.com/taosin/ai-engineering-interview-handbook/issues/new/choose)','', '## 参考与致谢','', '感谢 [agent-interview-hub](https://github.com/Zchary1106/agent-interview-hub) 对资料组织的启发。本项目独立维护题库与研习内容；参考范围、所读版本及内容边界见[致谢说明](ACKNOWLEDGEMENTS.md)。','', '## 许可','', '原创整理、结构化编排与代码采用 [MIT License](LICENSE)。外链文章、作者原文、商标及其他第三方内容维持原权利和许可，不因本仓库引用而变更。','','如需更正署名、日期或引用，请提交 Issue，不要公开个人敏感信息。']
    save(f,lines)
